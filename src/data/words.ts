let usedWords: Set<string> = new Set();

export function getRandomWord(): string {
  const remaining = ANSWER_WORDS.filter(w => !usedWords.has(w));
  const pool = remaining.length > 0 ? remaining : ANSWER_WORDS;
  if (remaining.length === 0) usedWords.clear();
  const word = pool[Math.floor(Math.random() * pool.length)];
  usedWords.add(word);
  return word;
}

export function isValidWord(word: string): boolean {
  return VALID_WORDS.has(word.toLowerCase());
}
